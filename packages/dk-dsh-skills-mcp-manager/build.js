import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const read = async path => (await readFile(new URL(path, import.meta.url), 'utf8')).replaceAll('\r\n', '\n');
let skills = await read('./vendor/skills/lib/client.js');
let mcp = await read('./vendor/mcp/lib/client.js');
// ponytail: pinned bundle anchors; revalidate this adapter when upgrading upstream.
const feedbackLinks = /,o\("div",\{className:"dssm-feedback-links"\}.*?e\("link.feedback"\)\)\)/;
assert(feedbackLinks.test(skills), 'Skills feedback links anchor changed');
skills = skills.replace(feedbackLinks, '');
const trashGuard = 'a.mutable&&n.linked!==!0&&s.push({value:"trash"';
assert(skills.includes(trashGuard), 'Skills delete action anchor changed');
skills = skills.replace(trashGuard, 'a.mutable&&n.linked!==!0&&n.sourceReadOnly!==!0&&s.push({value:"trash"');
const skillsDescription = ',o("p",{className:"dssm-desc"},e("desc"))';
const mcpDescription = "        h('p', { className: 'mcpm-desc', key: 'desc' }, t('desc')),\n";
assert(skills.includes(skillsDescription) && mcp.includes(mcpDescription), 'Page description anchors changed');
skills = skills.replace(skillsDescription, '');
mcp = mcp.replace(mcpDescription, '');
const primaryButton = '.mcpm-btn.primary { background: var(--dsw-alias-brand-primary); border-color: var(--dsw-alias-brand-primary); color: #fff; }';
assert(mcp.includes(primaryButton), 'MCP primary button anchor changed');
mcp = mcp.replace(primaryButton, primaryButton.replaceAll('--dsw-alias-brand-primary', '--dsw-alias-button-primary-fill').replace('#fff', 'var(--dsw-alias-label-primary-foreground)'));
const start = skills.indexOf('function an(r){');
const initEnd = skills.indexOf('var e;', start);
const end = skills.indexOf('module.exports.formatTrashTime=', initEnd);
assert(start > 0 && initEnd > start && end > initEnd, 'Skills activation anchors changed');
skills = skills.slice(0, initEnd) + '}module.exports.Page=ro;' + skills.slice(end);
const mcpStart = mcp.lastIndexOf('    return {\n      inject:');
assert(mcpStart > 0, 'MCP activation anchor changed');
mcp = mcp.slice(0, mcpStart) + `    return { Page: McpManagerPage, apply(ctx) {
      ctx.effect(() => ctx.locale.register(NS, DICT));
    } };
  },
});
`;
const wrap = source => {
  assert.equal(source.split('window.__ModuleLoader__.load(').length, 2);
  return source.replace('window.__ModuleLoader__.load(', '((module) => modules.push(module.factory))(');
};
const output = `// Generated by build.js; upstream licenses are in vendor/.
window.__ModuleLoader__.load({
  id: 'dk-dsh-skills-mcp-manager',
  factory(require) {
    const modules = [];
    ${wrap(skills)}
    ${wrap(mcp)}
    const skills = modules[0](require);
    const mcp = modules[1](require);
    ${await read('./client-main.js')}
  }
});
`;
await writeFile(new URL('./client.js', import.meta.url), output);
